/**
 * 系统级属性：所有物料共用（唯一名称 / 隐藏 / 样式 / 自定义类名）。
 * 这些不是组件 props，而是节点身份与节点级配置。
 */
function systemProps(
  options: { label?: boolean; style?: boolean; customClass?: boolean } = {},
): PropConfig[] {
  const { label = false, style = true, customClass = true } = options
  const configs: PropConfig[] = [
    {
      name: 'name',
      label: '唯一名称',
      control: 'name',
      group: 'common',
      description: '组件在页面内的唯一标识，事件与数据绑定通过它引用',
    },
    ...(label
      ? ([{ name: 'label', label: '标签', control: 'label', group: 'common', defaultValue: '' }] as PropConfig[])
      : []),
    {
      name: 'hidden',
      label: '隐藏',
      control: 'hidden',
      group: 'common',
      description: '隐藏后画布与运行时都不渲染',
    },
  ]
  if (style) {
    configs.push({
      name: 'style',
      label: '自定义样式',
      control: 'style',
      group: 'advanced',
      description: 'CSS 属性键值对，如 {"borderRadius":"8px"}',
    })
  }
  if (customClass) {
    configs.push({
      name: 'class',
      label: '自定义类名',
      control: 'custom-class',
      group: 'advanced',
      description: '取自「表单设置」中自定义 CSS 的类名',
    })
  }
  return configs
}

